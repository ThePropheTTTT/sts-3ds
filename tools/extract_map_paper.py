#!/usr/bin/env python3
"""Bake the three parchment slices of the act map into one texture page.

DungeonMap.renderNormalMap draws mapTop.png / mapMid.png / mapBot.png as three
1920x1080 images stacked on top of each other; it never stretches the middle
sheet.  The port used to crop one 5:3 slice out of mapMid and stretch it over
the whole tall map, which smeared the paper grain and the torn side edges.

This script keeps the natural aspect ratio.  The parchment is 1281 design px
wide (x 320..1601 in every sheet).  The crop is made symmetric about it: the
ornament on the left reaches x=239, so the same 81 px margin is kept on the
right.  The 1443 px crop maps onto the port's unified 320 px map width
(scale 0.2218), which leaves the 284 px parchment centred with 18 px of
dimmed scene on either side.  The three slices are trimmed to their alpha
bbox vertically (that is what carries the torn top/bottom edges) and stacked
in one 512x1024 page.

    python tools/extract_map_paper.py
        -> assets/map_paper.png
        -> port/source/map_paper_gen.h
"""

from __future__ import annotations

import argparse
import os

from PIL import Image

from sts_assets import Jar

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_JAR = os.environ.get("STS_JAR", "desktop-1.0.jar")

PAGE_W, PAGE_H = 512, 1024
PAPER_W = 320                  # the port's unified map width
SOURCES = [
    ("top", "images/ui/map/mapTop.png"),
    ("mid", "images/ui/map/mapMid.png"),
    ("bot", "images/ui/map/mapBot.png"),
]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--jar", default=DEFAULT_JAR)
    ap.add_argument("--out", default=os.path.join(HERE, "assets/map_paper.png"))
    ap.add_argument("--header", default=os.path.join(HERE, "port/source/map_paper_gen.h"))
    args = ap.parse_args(argv)

    jar = Jar(args.jar)
    sheets = []
    for name, path in SOURCES:
        im = jar.image(path).convert("RGBA")
        bbox = im.getchannel("A").getbbox()
        if bbox is None:
            raise SystemExit(f"{path}: no opaque pixels")
        sheets.append((name, path, im, bbox))

    # All three slices have to share one horizontal crop or their side
    # ornaments stop lining up.  The parchment itself is x 320..1601 in every
    # sheet; the top slice also carries an ornament that reaches x=239.
    left = min(s[3][0] for s in sheets)
    paper_right = max(s[3][2] for s in sheets)
    # Keep the parchment itself centred: whatever ornament sticks out on the
    # left is mirrored as empty scene on the right, so the 3DS screen does not
    # end up with the paper flush against one edge.
    right = min(sheets[0][2].width, paper_right + (320 - left))
    crop_w = right - left
    if crop_w <= 0:
        raise SystemExit("empty horizontal crop")

    page = Image.new("RGBA", (PAGE_W, PAGE_H), (0, 0, 0, 0))
    rects = {}
    y = 0
    for name, path, im, bbox in sheets:
        crop = im.crop((left, bbox[1], right, bbox[3]))
        h = max(1, int(round(crop.height * PAPER_W / crop_w)))
        out = crop.resize((PAPER_W, h), Image.LANCZOS)
        if y + h > PAGE_H:
            raise SystemExit(f"paper slices do not fit in {PAGE_W}x{PAGE_H}: need {y + h}")
        page.alpha_composite(out, (0, y))
        rects[name] = (0, y, PAPER_W, h)
        print(f"{name:3s} {path.split('/')[-1]:10s} crop=({left},{bbox[1]},{right},{bbox[3]}) "
              f"-> {PAPER_W}x{h} at y={y}")
        y += h

    scale = PAPER_W / float(crop_w)
    paper_w = int(round(1281 * scale))
    paper_left = int(round((320 - left) * scale))

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    page.save(args.out)
    print(f"-> {args.out} ({PAGE_W}x{PAGE_H}, paper ends at {y})")

    header = [
        "/* Generated by tools/extract_map_paper.py -- do not edit. */",
        "#pragma once",
        "",
        f"#define STS_MAP_PAPER_PAGE_W {PAGE_W}",
        f"#define STS_MAP_PAPER_PAGE_H {PAGE_H}",
        f"#define STS_MAP_PAPER_CROP_W {crop_w}",
        f"#define STS_MAP_PAPER_LEFT {left}",
        f"#define STS_MAP_PAPER_W {PAPER_W}",
        f"#define STS_MAP_PAPER_PAPER_W {paper_w}",
        f"#define STS_MAP_PAPER_PAPER_LEFT {paper_left}",
        "",
        "/* mapTop/mapMid/mapBot share one horizontal crop, scaled to the port's",
        " * 320 px map width in natural aspect (no stretching).  PAPER_LEFT is the",
        " * parchment's left edge inside that crop; the rest is torn-edge ornament. */",
    ]
    for name, _ in SOURCES:
        x, ry, w, h = rects[name]
        header.append("static const int sts_map_paper_%s[4] = {%d, %d, %d, %d};" %
                      (name, x, ry, w, h))
    header.append("")

    os.makedirs(os.path.dirname(args.header), exist_ok=True)
    with open(args.header, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(header))
    print(f"-> {args.header}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
