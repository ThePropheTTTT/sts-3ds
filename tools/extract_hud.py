#!/usr/bin/env python3
"""Extract the in-game HUD art into one atlas page.

The pieces are the game's own images:

* images/ui/topPanel/red/layer1..6.png -- EnergyOrbRed's six rotating layers,
  plus layer1d..5d for the empty-orb art.
* images/ui/topPanel/endTurnButton.png, endTurnButtonGlow.png and
  endTurnHover.png -- EndTurnButton's base, glow and hover hexagons.
* images/ui/topPanel/energyRedVFX.png -- the flash EnergyPanel draws when the
  orb's value changes.
* images/ui/campfire/sleep.png, smith.png, outline.png and buttonShadow.png --
  AbstractCampfireOption's button art, focus outline and shadow.

    python tools/extract_hud.py  -> assets/hud.png, port/source/hud_gen.h
"""

from __future__ import annotations

import argparse
import os

from PIL import Image

from sts_assets import Jar

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_JAR = os.environ.get("STS_JAR", "desktop-1.0.jar")

PAGE_W = 1024
# PICA200 textures need power-of-two dimensions, so the page is square even
# though only the top 768 rows carry art.
PAGE_H = 1024

# The orb and campfire art are 256 canvases; the energy layers are 128.
ORB = 128
BUTTON = 256

ENERGY_BOX = [(i * ORB, 0, ORB, ORB) for i in range(6)]
ENERGY_DIM_BOX = [(i * ORB, ORB, ORB, ORB) for i in range(5)]
END_BOX = [(i * BUTTON, 256, BUTTON, BUTTON) for i in range(3)]
VFX_BOX = (768, 256, BUTTON, BUTTON)
CAMP_BOX = [(i * BUTTON, 512, BUTTON, BUTTON) for i in range(4)]

END_NAMES = ["endTurnButton.png", "endTurnButtonGlow.png", "endTurnHover.png"]
CAMP_NAMES = ["sleep.png", "smith.png", "outline.png", "buttonShadow.png"]


def tint_alpha(im: Image.Image, rgb, alpha_scale: float = 1.0) -> Image.Image:
    """Replace RGB with a fill colour while keeping the source alpha."""
    out = Image.new("RGBA", im.size, (rgb[0], rgb[1], rgb[2], 255))
    a = im.getchannel("A")
    if alpha_scale != 1.0:
        a = a.point(lambda v: int(v * alpha_scale + 0.5))
    out.putalpha(a)
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--jar", default=DEFAULT_JAR)
    ap.add_argument("--out", default=os.path.join(HERE, "assets/hud.png"))
    ap.add_argument("--header", default=os.path.join(HERE, "port/source/hud_gen.h"))
    args = ap.parse_args(argv)

    page = Image.new("RGBA", (PAGE_W, PAGE_H), (0, 0, 0, 0))
    jar = Jar(args.jar)

    for i in range(6):
        im = jar.image("images/ui/topPanel/red/layer%d.png" % (i + 1)).convert("RGBA")
        x, y, w, h = ENERGY_BOX[i]
        page.alpha_composite(im.resize((w, h), Image.LANCZOS), (x, y))
        print(f"energy layer {i + 1}        {im.width}x{im.height} -> {x},{y}")
    for i in range(5):
        im = jar.image("images/ui/topPanel/red/layer%dd.png" % (i + 1)).convert("RGBA")
        x, y, w, h = ENERGY_DIM_BOX[i]
        page.alpha_composite(im.resize((w, h), Image.LANCZOS), (x, y))
        print(f"energy dim {i + 1}          {im.width}x{im.height} -> {x},{y}")
    for i, name in enumerate(END_NAMES):
        im = jar.image("images/ui/topPanel/" + name).convert("RGBA")
        x, y, w, h = END_BOX[i]
        page.alpha_composite(im.resize((w, h), Image.LANCZOS), (x, y))
        print(f"end turn {name:20s} {im.width}x{im.height} -> {x},{y}")
    vfx = jar.image("images/ui/topPanel/energyRedVFX.png").convert("RGBA")
    page.alpha_composite(vfx.resize((BUTTON, BUTTON), Image.LANCZOS), VFX_BOX[:2])
    print(f"energy VFX              {vfx.width}x{vfx.height} -> {VFX_BOX[0]},{VFX_BOX[1]}")

    for i, name in enumerate(CAMP_NAMES):
        im = jar.image("images/ui/campfire/" + name).convert("RGBA")
        if name == "outline.png":
            # AbstractCampfireOption draws the white outline in gold, behind the
            # button at scale*1.075 so only a rim shows.
            im = tint_alpha(im, (255, 237, 115))
        elif name == "buttonShadow.png":
            # The shadow is drawn with colour.a/5 = 0.2, not as solid black.
            im = tint_alpha(im, (0, 0, 0), 0.2)
        x, y, w, h = CAMP_BOX[i]
        page.alpha_composite(im.resize((w, h), Image.LANCZOS), (x, y))
        print(f"campfire {name:18s} {im.width}x{im.height} -> {x},{y}")

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    page.save(args.out)
    print(f"-> {args.out} ({page.width}x{page.height})")

    header = [
        "/* Generated by tools/extract_hud.py -- do not edit. */",
        "#pragma once",
        "",
        "#define STS_HUD_PAGE_W %d" % PAGE_W,
        "#define STS_HUD_PAGE_H %d" % PAGE_H,
        "",
        "typedef struct { short x, y; unsigned short w, h; } StsHudRect;",
        "",
        "/* EnergyOrbRed: six layers, plus five dim layers for an empty orb. */",
        "static const StsHudRect sts_hud_energy[6] = {",
    ]
    for i, box in enumerate(ENERGY_BOX):
        header.append("    {%d, %d, %d, %d}, /* layer%d */" % (box + (i + 1,)))
    header.append("};")
    header.append("static const StsHudRect sts_hud_energy_dim[5] = {")
    for i, box in enumerate(ENERGY_DIM_BOX):
        header.append("    {%d, %d, %d, %d}, /* layer%dd */" % (box + (i + 1,)))
    header.append("};")
    header.append("")
    header.append("/* EndTurnButton: base, glow and hover. */")
    header.append("enum { STS_HUD_END_TURN = 0, STS_HUD_END_GLOW, STS_HUD_END_HOVER, STS_HUD_END_COUNT };")
    header.append("static const StsHudRect sts_hud_end[STS_HUD_END_COUNT] = {")
    for i, box in enumerate(END_BOX):
        header.append("    {%d, %d, %d, %d}, /* %s */" % (box + (END_NAMES[i],)))
    header.append("};")
    header.append("")
    header.append("/* EnergyPanel's two-second flash. */")
    header.append("static const StsHudRect sts_hud_vfx = {%d, %d, %d, %d};" % VFX_BOX)
    header.append("")
    header.append("/* AbstractCampfireOption: sleep, smith, focus outline, shadow. */")
    header.append("enum { STS_HUD_CAMP_SLEEP = 0, STS_HUD_CAMP_SMITH, STS_HUD_CAMP_OUTLINE,")
    header.append("       STS_HUD_CAMP_SHADOW, STS_HUD_CAMP_COUNT };")
    header.append("static const StsHudRect sts_hud_camp[STS_HUD_CAMP_COUNT] = {")
    for i, box in enumerate(CAMP_BOX):
        header.append("    {%d, %d, %d, %d}, /* %s */" % (box + (CAMP_NAMES[i],)))
    header.append("};")
    header.append("")
    with open(args.header, "w", encoding="utf-8") as fh:
        fh.write("\n".join(header))
    print(f"-> {args.header}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
