#!/usr/bin/env python3
"""Generate port/source/l10n_gen.h: status and event text straight from the game.

Status descriptions are assembled from the game's own power text segments so the
wording stays vanilla (the only thing we inject are the numbers the segments
leave blank). Events take their body text and option labels from events.json;
the numeric effects are decided in run.c because the game's event logic is code.

    python tools/gen_l10n.py
"""

from __future__ import annotations

import argparse
import json
import os
import re

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

MARKUP = re.compile(r"#[a-zA-Z]|[@~]")


def clean(text: str) -> str:
    text = MARKUP.sub("", text or "")
    text = text.replace(" NL ", "\n").replace("NL ", "\n").replace(" NL", "\n")
    return text.replace("  ", " ").strip()


def c_string(text: str) -> str:
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def tidy(text: str) -> str:
    """Drop the spaces the game inserts around highlighted words."""
    for ch in "。，、；：？！）":
        text = text.replace(" " + ch, ch)
    text = text.replace("（ ", "（").replace(" ）", "）")
    while "  " in text:
        text = text.replace("  ", " ")
    return text.strip()


def power_text(powers: dict, key: str, segments: list[int], numbers: list[str]) -> str:
    """Assemble the game's own segments, injecting numbers where they go."""
    entry = powers.get(key)
    if not entry:
        return ""
    raw = entry.get("DESCRIPTIONS", [])
    out = ""
    for i, idx in enumerate(segments):
        if idx < len(raw):
            out += clean(raw[idx])
        if i < len(numbers):
            out += numbers[i]
    return tidy(out)


def event_text(events: dict, key: str) -> dict | None:
    entry = events.get(key)
    if not entry:
        return None
    body = clean(entry["DESCRIPTIONS"][0])
    # Option labels are split across segments; join everything, then split on [..].
    joined = "".join(entry.get("OPTIONS", []))
    joined = clean(joined)
    labels = re.findall(r"\[([^\]]+)\]", joined)
    return {
        "name": clean(entry.get("NAME", key)),
        "body": body,
        "labels": labels,
        "descriptions": [clean(x) for x in entry.get("DESCRIPTIONS", [])],
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", default=HERE)
    ap.add_argument("--out", default=None)
    args = ap.parse_args(argv)

    l10n = os.path.join(args.root, "assets/data/l10n")
    with open(os.path.join(l10n, "powers.json"), encoding="utf-8") as fp:
        powers = json.load(fp)
    with open(os.path.join(l10n, "events.json"), encoding="utf-8") as fp:
        events = json.load(fp)
    with open(os.path.join(l10n, "relics.json"), encoding="utf-8") as fp:
        relics = json.load(fp)

    # Vulnerable: "从攻击受到的伤害增加 50%。持续时间 N 回合。"
    vulnerable = power_text(powers, "Vulnerable", [0, 1, 2], ["50", "%d"])
    weakened = power_text(powers, "Weakened", [0, 1, 2], ["25", "%d"])
    strength = power_text(powers, "Strength", [0, 2], ["%d"])

    wanted = ["Big Fish", "The Cleric", "World of Goop"]
    picked = []
    for key in wanted:
        entry = event_text(events, key)
        if entry:
            picked.append((key, entry))

    out_path = args.out or os.path.join(args.root, "port/source/l10n_gen.h")
    lines = [
        "/* Generated by tools/gen_l10n.py -- text comes from the game's own JSON. */",
        "#ifndef STS_L10N_GEN_H",
        "#define STS_L10N_GEN_H",
        "",
        "typedef struct { const char *name; const char *desc; } StatusText;",
        "",
        "static const StatusText sts_status_text[] = {",
        f"    {{{c_string(powers['Vulnerable']['NAME'])}, {c_string(vulnerable)}}},",
        f"    {{{c_string(powers['Weakened']['NAME'])}, {c_string(weakened)}}},",
        f"    {{{c_string(powers['Strength']['NAME'])}, {c_string(strength)}}},",
        "};",
        "",
        "typedef struct {",
        "    const char *name;",
        "    const char *body;",
        "    const char *option[3];",
        "    const char *option_desc[3];",
        "    const char *result[3];",
        "} EventText;",
        "",
        f"#define STS_EVENT_COUNT {len(picked)}",
        "static const EventText sts_events[] = {",
    ]

    # Effects live in run.c; the descriptions below must match them.
    desc = {
        "Big Fish": ["回复 1/3 最大生命", "最大生命 +5", "获得一件遗物（诅咒待接入）"],
        "The Cleric": ["35 金币：回复 25% 最大生命", "50 金币：移除一张牌", "离开"],
        "World of Goop": ["+75 金币，失去 11 生命", "失去 20–50 金币", "离开"],
    }
    label_override = {
        "Big Fish": ["香蕉", "甜甜圈", "盒子"],
        "The Cleric": ["治疗", "净化", "离开"],
        "World of Goop": ["收集金币", "放手吧", "离开"],
    }
    # The result page comes from the game's own DESCRIPTIONS; the indices are
    # the ones BigFish.java/Cleric.java/GoopPuddle.java pass to updateBodyText.
    result_pick = {
        "Big Fish": [(1,), (2,), (4, 5)],
        "The Cleric": [(1,), (2,), (3,)],
        "World of Goop": [(1,), (2,), (2,)],
    }
    for key, entry in picked:
        labels = label_override.get(key, entry["labels"] + ["离开"] * 3)
        d = desc.get(key, ["", ""])
        descs = entry["descriptions"]
        result = []
        for picks in result_pick.get(key, [(), (), ()]):
            result.append("".join(descs[i] for i in picks if i < len(descs)).strip())
        while len(result) < 3:
            result.append("")
        lines.append(
            "    {%s, %s, {%s, %s, %s}, {%s, %s, %s}, {%s, %s, %s}},"
            % (
                c_string(entry["name"]),
                c_string(entry["body"]),
                c_string(labels[0]),
                c_string(labels[1]),
                c_string(labels[2]),
                c_string(d[0]),
                c_string(d[1]),
                c_string(d[2]),
                c_string(result[0]),
                c_string(result[1]),
                c_string(result[2]),
            )
        )
    lines += ["};", ""]

    # Relic descriptions, in the same order as the RELIC_* enum in battle.c.
    relic_ids = [
        "Burning Blood", "Vajra", "Anchor", "Bag of Preparation", "Blood Vial",
        "Lantern", "Bag of Marbles", "Strawberry", "Orichalcum", "Red Skull",
        "Pen Nib", "Nunchaku", "Art of War", "Toy Ornithopter", "Golden Idol",
        "Bronze Scales",
    ]
    lines += [
        "static const char *const sts_relic_desc[] __attribute__((unused)) = {",
    ]
    # The game splits relic text around the numbers its code injects.
    relic_nums = {
        "Burning Blood": [6], "Vajra": [1], "Anchor": [10],
        "Bag of Preparation": [2], "Blood Vial": [2], "Lantern": [1],
        "Bag of Marbles": [1], "Strawberry": [7], "Orichalcum": [6],
        "Red Skull": [50, 3], "Pen Nib": [10], "Nunchaku": [10],
        "Art of War": [1], "Toy Ornithopter": [5], "Golden Idol": [25],
        "Bronze Scales": [3],
    }
    for rid in relic_ids:
        entry = relics.get(rid, {})
        segs = [clean(x) for x in entry.get("DESCRIPTIONS", [])]
        nums = relic_nums.get(rid, [])
        text = ""
        for i, seg in enumerate(segs):
            text += seg
            if i < len(nums):
                text += str(nums[i])
        lines.append("    %s," % c_string(tidy(text)))
    lines += ["};", "", "#endif", ""]

    with open(out_path, "w", encoding="utf-8", newline="\n") as fp:
        fp.write("\n".join(lines))
    print(f"wrote {out_path}: {len(picked)} events")
    for key, entry in picked:
        print(f"  {key}: {entry['name']} / {entry['labels'][:2]}")
    print(f"  statuses: {vulnerable} | {weakened} | {strength}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
