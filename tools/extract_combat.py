#!/usr/bin/env python3
"""Extract the combat HUD art the port needs into one small atlas page.

The pieces come straight from the game:

* images/ui/combat/block.png -- the 64x64 shield AbstractCreature draws behind
  the block number.
* powers/powers.png -- the 48x48 power icons.  AbstractPower.renderIcons draws
  the 48px variant at Settings.scale, so that is the one we take.
* images/characters/ironclad/idle -- the battle rig.  The 3DS has no Spine
  runtime, so the setup pose is baked flat once (tools/bake_spine.py), exactly
  like the monsters.  The old shoulder.png close-up was only a bust.

    python tools/extract_combat.py   -> assets/combat.png, port/source/combat_gen.h
"""

from __future__ import annotations

import argparse
import io
import os
import zipfile

from PIL import Image

import bake_spine
from sts_assets import Jar, parse_atlas

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_JAR = os.environ.get("STS_JAR", "desktop-1.0.jar")

PAGE = 512
BLOCK_BOX = (0, 0, 64, 64)
# 48px icons: four on row 0, two on row 1, then the act 2 powers on row 2.
POWER_BOX = [(64 + 48 * i, 0, 48, 48) for i in range(4)] + \
            [(64 + 48 * i, 48, 48, 48) for i in range(2)] + \
            [(64 + 48 * i, 96, 48, 48) for i in range(5)]
PLAYER_BOX = (0, 160, 96, 136)
PLAYER_RECT = [0, 160, 96, 136]  # filled in by main(): fitted inside PLAYER_BOX

# Order must match STS_POWER_* in port/source/combat_gen.h.  MetallicizePower
# loads powers.atlas region "armor" (there is no "metallicize" region).
POWERS = ["strength", "dexterity", "vulnerable", "weak", "frail", "armor",
          "flight", "platedarmor", "artifact", "barricade", "hex"]


def region_on_canvas(page: Image.Image, region) -> Image.Image:
    """Rebuild a region's original canvas so its offset survives the trim.

    libGDX packs the trimmed pixels but keeps (orig, offset) so the sprite can
    be drawn at its canonical place; the power amount text is aligned to that
    canvas, so dropping the trim would shift the icons.
    """
    piece = page.crop((region.x, region.y, region.x + region.w, region.y + region.h))
    canvas = Image.new("RGBA", tuple(region.orig), (0, 0, 0, 0))
    top = region.orig[1] - region.offset[1] - piece.height
    canvas.alpha_composite(piece, (region.offset[0], top))
    return canvas


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--jar", default=DEFAULT_JAR)
    ap.add_argument("--out", default=os.path.join(HERE, "assets/combat.png"))
    ap.add_argument("--header", default=os.path.join(HERE, "port/source/combat_gen.h"))
    args = ap.parse_args(argv)

    page = Image.new("RGBA", (PAGE, PAGE), (0, 0, 0, 0))
    jar = Jar(args.jar)

    block = jar.image("images/ui/combat/block.png").convert("RGBA")
    x, y, w, h = BLOCK_BOX
    page.alpha_composite(block.resize((w, h), Image.LANCZOS), (x, y))
    print(f"block                   {block.width}x{block.height} -> {x},{y} {w}x{h}")

    pages, regions = parse_atlas(jar.text("powers/powers.atlas"))
    # The atlas lists its page by bare file name; it lives next to the atlas.
    atlas = jar.image("powers/" + pages[0]).convert("RGBA")
    for i, name in enumerate(POWERS):
        key = "48/" + name
        if key not in regions:
            raise SystemExit(f"powers.atlas has no region {key}")
        icon = region_on_canvas(atlas, regions[key])
        x, y, w, h = POWER_BOX[i]
        page.alpha_composite(icon.resize((w, h), Image.LANCZOS), (x, y))
        print(f"power {name:12s}       {key} -> {x},{y} {w}x{h}")

    bake_spine.JAR = args.jar
    # The setup pose is a deep crouch; the Idle animation starts in the wide
    # combat stance the game shows, so sample it at t=0.
    player = bake_spine.bake("images/characters/ironclad/idle", {}, out_size=200, anim="Idle")
    if player is None:
        raise SystemExit("could not bake images/characters/ironclad/idle")
    bbox = player.getchannel("A").getbbox()
    if bbox:
        player = player.crop(bbox)
    x, y, w, h = PLAYER_BOX
    # Keep the aspect ratio: the baked knight is taller than it is wide.
    scale = min(w / player.width, h / player.height)
    pw = max(1, round(player.width * scale))
    ph = max(1, round(player.height * scale))
    px = x + (w - pw) // 2
    py = y + (h - ph) // 2
    page.alpha_composite(player.resize((pw, ph), Image.LANCZOS), (px, py))
    PLAYER_RECT[:] = [px, py, pw, ph]
    print(f"player (ironclad)       {player.width}x{player.height} -> {px},{py} {pw}x{ph}")

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    page.save(args.out)
    print(f"-> {args.out} ({page.width}x{page.height})")

    header = [
        "/* Generated by tools/extract_combat.py -- do not edit. */",
        "#pragma once",
        "",
        f"#define STS_COMBAT_PAGE {PAGE}",
        "",
        "typedef struct { unsigned short x, y, w, h; } StsCombatRect;",
        "",
        "/* AbstractCreature.BLOCK_ICON: images/ui/combat/block.png (64x64). */",
        "static const StsCombatRect sts_combat_block = {%d, %d, %d, %d};" % BLOCK_BOX,
        "",
        "/* AbstractPower.renderIcons draws the 48px tile (powers/powers.atlas).",
        " * MetallicizePower.loadRegion(\"armor\"), hence the STS_POWER_METALLICIZE name. */",
        "enum { " + ", ".join(
            "STS_POWER_" + ("METALLICIZE" if p == "armor" else p.upper()) for p in POWERS
        ) + ",",
        "       STS_POWER_COUNT };",
        "static const StsCombatRect sts_combat_power[STS_POWER_COUNT] = {",
    ]
    for i in range(len(POWERS)):
        header.append("    {%d, %d, %d, %d}, /* %s */" % (POWER_BOX[i] + (POWERS[i],)))
    header.append("};")
    header.append("")
    header.append("/* images/characters/ironclad/idle, Idle animation at t=0 (Spine setup pose is a crouch). */")
    header.append("static const StsCombatRect sts_combat_player = {%d, %d, %d, %d};" % tuple(PLAYER_RECT))
    header.append("")
    with open(args.header, "w", encoding="utf-8") as fh:
        fh.write("\n".join(header))
    print(f"-> {args.header}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
